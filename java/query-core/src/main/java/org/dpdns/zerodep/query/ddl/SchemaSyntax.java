package org.dpdns.zerodep.query.ddl;

import org.dpdns.zerodep.query.dialect.Dialect;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * 一个方言的结构变更写法：类型名、建表、加列、改列、索引、外键，以及从系统目录读回表的结构。
 * 由方言包实现（{@code HanaDialect.schemaSyntax()} 等），{@link SchemaTools} 用它比较声明与实库、生成语句。
 * 每个方法返回一条 JDBC 语句，不拼多语句。
 */
public abstract class SchemaSyntax {
    /** 系统目录查询：执行带 {@code ?} 参数的 SELECT，每行是列标签（小写）到值的映射。 */
    @FunctionalInterface
    public interface Catalog {
        /** 执行 sql 并返回全部行。 */
        List<Map<String, Object>> rows(String sql, Object... parameters);
    }

    /** 方言，用于引号。 */
    protected final Dialect dialect;

    /** 由方言包的子类调用。 */
    protected SchemaSyntax(Dialect dialect) { this.dialect = dialect; }

    /** 列类型在本方言里的类型名。 */
    public abstract String typeName(ColumnType type);

    /** 读取 schema（为空表示连接当前的 schema）里 table 的结构；表不存在时返回 null。 */
    public abstract TableDef read(Catalog catalog, String schema, String table);

    /** 能否就地改成不是放宽的类型（缩短、改类型族）；HANA 不能（实测报 feature not supported）。 */
    public boolean changesTypesInPlace() { return true; }

    /** DDL 是否能在事务里回滚（PostgreSQL 能，MySQL 每条隐式提交，HANA 默认自动提交）。 */
    public boolean transactionalDdl() { return false; }

    /**
     * 声明的类型在本方言里实际会存成什么，用于与目录比较：例如 PostgreSQL 的定长字节存成 BYTEA（不限长度），
     * HANA 超过 5000 的文本存成 NCLOB。默认原样返回。
     */
    public ColumnType stored(ColumnType declared) { return declared; }

    // ---------- 建表 ----------

    /** 建表的语句：CREATE TABLE（含主键）、表和列的注释、索引；外键另由 {@link #addForeignKey} 在最后建。 */
    public List<String> createTable(TableDef t) {
        List<String> out = new ArrayList<>();
        StringBuilder sql = new StringBuilder(createKeyword()).append(" ").append(table(t)).append(" (");
        for (int i = 0; i < t.columns().size(); i++) {
            if (i > 0) sql.append(", ");
            sql.append(columnDefinition(t.columns().get(i)));
        }
        if (!t.primaryKey().isEmpty()) sql.append(", PRIMARY KEY (").append(names(t.primaryKey())).append(")");
        sql.append(")").append(tableOptions(t));
        for (TableDef.Option o : t.options()) {
            if (o.dialect().isInstance(dialect)) sql.append(" ").append(o.sql());
        }
        out.add(sql.toString());
        out.addAll(comments(t));
        for (TableDef.Index i : t.indexes()) out.add(createIndex(t, i));
        return out;
    }

    /** CREATE TABLE 的关键字；HANA 写成 {@code CREATE COLUMN TABLE}。 */
    protected String createKeyword() { return "CREATE TABLE"; }

    /** 建表语句末尾、各方言的 {@code @TableOption} 之前的选项，例如 MySQL 的表注释；默认没有。 */
    protected String tableOptions(TableDef t) { return ""; }

    /** 表和列的注释语句；默认写成 {@code COMMENT ON ... IS '...'}，MySQL 写在列定义和表选项里。 */
    protected List<String> comments(TableDef t) {
        List<String> out = new ArrayList<>();
        if (!t.comment().isEmpty()) out.add("COMMENT ON TABLE " + table(t) + " IS " + literal(t.comment()));
        for (TableDef.Column c : t.columns()) {
            if (!c.comment().isEmpty()) out.add("COMMENT ON COLUMN " + table(t) + "." + quote(c.name()) + " IS " + literal(c.comment()));
        }
        return out;
    }

    /** 一列的定义：名字、类型、自增、默认值、NOT NULL；MySQL 另有顺序和注释。 */
    public String columnDefinition(TableDef.Column c) {
        StringBuilder sql = new StringBuilder(quote(c.name())).append(" ").append(typeName(c.type()));
        if (c.identity()) sql.append(" GENERATED BY DEFAULT AS IDENTITY");
        if (!c.defaultValue().isEmpty()) sql.append(" DEFAULT ").append(c.defaultValue());
        if (!c.nullable()) sql.append(" NOT NULL");
        return sql.toString();
    }

    // ---------- 改表 ----------

    /** 加一列。 */
    public String addColumn(TableDef t, TableDef.Column c) { return "ALTER TABLE " + table(t) + " ADD COLUMN " + columnDefinition(c); }

    /** 把列改成 c 的类型（保持 c 的可空和默认值）。 */
    public String alterType(TableDef t, TableDef.Column c) { return "ALTER TABLE " + table(t) + " ALTER COLUMN " + quote(c.name()) + " TYPE " + typeName(c.type()); }

    /** 允许 NULL。 */
    public String dropNotNull(TableDef t, TableDef.Column c) { return "ALTER TABLE " + table(t) + " ALTER COLUMN " + quote(c.name()) + " DROP NOT NULL"; }

    /** 不允许 NULL；已有 NULL 时数据库报错。 */
    public String setNotNull(TableDef t, TableDef.Column c) { return "ALTER TABLE " + table(t) + " ALTER COLUMN " + quote(c.name()) + " SET NOT NULL"; }

    /** 改默认值为 c 的默认值。 */
    public String setDefault(TableDef t, TableDef.Column c) {
        return "ALTER TABLE " + table(t) + " ALTER COLUMN " + quote(c.name()) + " SET DEFAULT " + c.defaultValue();
    }

    /** 把列 from 改名为 to。 */
    public String renameColumn(TableDef t, String from, String to) {
        return "ALTER TABLE " + table(t) + " RENAME COLUMN " + quote(from) + " TO " + quote(to);
    }

    /** 建索引。 */
    public String createIndex(TableDef t, TableDef.Index i) {
        return "CREATE " + (i.unique() ? "UNIQUE " : "") + "INDEX " + quote(i.name()) + " ON " + table(t) + " (" + names(i.columns()) + ")";
    }

    /** 加外键。 */
    public String addForeignKey(TableDef t, TableDef.ForeignKey f) {
        String target = f.referencedSchema().isEmpty() ? quote(f.referencedTable()) : quote(f.referencedSchema()) + "." + quote(f.referencedTable());
        return "ALTER TABLE " + table(t) + " ADD CONSTRAINT " + quote(f.name()) + " FOREIGN KEY (" + names(f.columns()) + ") REFERENCES " + target
            + " (" + names(f.referencedColumns()) + ")";
    }

    // ---------- 比较 ----------

    /**
     * 默认值归一化后再比较：去掉外层括号、PostgreSQL 的 {@code ::类型} 后缀和单引号，忽略大小写。
     * 各库的目录里写法不同（HANA 已经去掉引号，PostgreSQL 带类型转换），所以只比较归一化的结果。
     */
    public String normalizeDefault(String value) {
        if (value == null) return "";
        String v = value.trim();
        while (v.startsWith("(") && v.endsWith(")")) v = v.substring(1, v.length() - 1).trim();
        v = withoutCast(v);
        if (v.startsWith("'") && v.endsWith("'") && v.length() >= 2) v = v.substring(1, v.length() - 1).replace("''", "'");
        return v.toUpperCase(Locale.ROOT);
    }

    // ---------- 读取 ----------

    /**
     * 目录里去掉了引号的默认值（HANA、MySQL 的写法）还原成 SQL：文本、日期和时间列的常量加单引号，
     * 数字和 {@code CURRENT_*} 这类函数原样；没有默认值时返回空串。读回的模型因此与声明的写法一致，生成代码时三库相同。
     */
    protected static String sqlDefault(String raw, ColumnType type) {
        if (raw == null || raw.isEmpty()) return "";
        boolean quoted = switch (type.kind()) {
            case TEXT, CLOB, DATE, TIMESTAMP -> !raw.matches("(?i)CURRENT_\\w+(\\(\\d*\\))?");
            default -> false;
        };
        return quoted ? "'" + raw.replace("'", "''") + "'" : raw;
    }

    /** PostgreSQL 目录里的默认值去掉 {@code ::类型} 后缀，例如 {@code 'open'::character varying} 读成 {@code 'open'}。 */
    protected static String withoutCast(String raw) {
        return raw == null ? "" : raw.replaceAll("::[a-zA-Z ]+(\\(\\d+(,\\d+)?\\))?(\\[])?$", "");
    }

    // ---------- 共用 ----------

    /** 写出 {@code schema.表名}。 */
    protected String table(TableDef t) { return t.schema().isEmpty() ? quote(t.name()) : quote(t.schema()) + "." + quote(t.name()); }

    /** 按方言需要加引号的标识符。 */
    protected String quote(String identifier) { return dialect.quote(identifier); }

    /** 逗号连接的列名。 */
    protected String names(List<String> columns) { return String.join(", ", columns.stream().map(this::quote).toList()); }

    /** 文本字面量。 */
    protected String literal(String text) { return "'" + text.replace("'", "''") + "'"; }

    /** 目录里的数值（Integer、Long、BigDecimal 都可能）转成 int；null 为 0。 */
    protected static int number(Object value) { return value == null ? 0 : ((Number) value).intValue(); }

    /** 目录里的文本；null 为空串。 */
    protected static String text(Object value) { return value == null ? "" : value.toString(); }
}
