    @Test
    void 追踪范围结束时只写回变了的行并把新版本写回对象() {
        insertDocs();
        Writes.DocBean d1 = db.tracked(t -> {
            List<Writes.DocBean> all = t.list(Writes.Doc.class, docBeans());
            all.get(0).setTitle("a2");
            return all.get(0);
        });
        assertEquals(List.of("D1:a2:2", "D2:b:1"), docs());
        assertEquals(2, d1.getVersion());
        db.tracking(t -> {
            Writes.DocBean again = t.one(Writes.Doc.class, docBean("D1"));
            again.setTitle("a3");
            again.setTitle("a2");
        });
        assertEquals(List.of("D1:a2:2", "D2:b:1"), docs(), "a row changed back is not written");
    }

    @Test
    void 追踪范围里同一主键只登记一份且嵌套范围由最外层写回() {
        insertDocs();
        db.tracking(t -> {
            Writes.DocBean first = t.one(Writes.Doc.class, docBean("D1"));
            first.setTitle("x");
            db.tracking(inner -> {
                Writes.DocBean same = inner.one(Writes.Doc.class, docBean("D1"));
                assertSame(first, same);
                same.setTitle("y");
            });
            assertEquals(List.of("D1:a:1", "D2:b:1"), docs(), "the inner scope does not write");
        });
        assertEquals(List.of("D1:y:2", "D2:b:1"), docs());
    }

    @Test
    void 追踪范围抛出异常或写回冲突时不写也不改对象的版本() {
        insertDocs();
        assertThrows(IllegalStateException.class, () -> db.tracking(t -> {
            t.one(Writes.Doc.class, docBean("D1")).setTitle("lost");
            throw new IllegalStateException("abort");
        }));
        assertEquals(List.of("D1:a:1", "D2:b:1"), docs());
        Writes.DocBean[] held = new Writes.DocBean[1];
        assertThrows(UnexpectedRowCountException.class, () -> db.tracking(t -> {
            held[0] = t.one(Writes.Doc.class, docBean("D1"));
            held[0].setTitle("mine");
            db.execute(Writes.renameDoc(new Writes.DocRow("D1", "theirs", 1)));
        }));
        assertEquals(List.of("D1:theirs:2", "D2:b:1"), docs());
        assertEquals(1, held[0].getVersion(), "a failed write leaves the version as read");
    }

