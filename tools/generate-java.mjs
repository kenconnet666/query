function sqlValues() {
  const m = [];
  for (const v of JAVA_VALUES) {
    const F = `Expr${v.of}`;
    m.push(`    /** 绑定参数，结果是 {@code ${F}}；在 SELECT 列表等位置会写成字面量。 */
    public static ${F}<${v.java}> val(${v.java} value) { return ${F}.of(param(value)); }`);
    m.push(`    /** 写进 SQL 文本的字面量，结果是 {@code ${F}}；只用于代码里的固定常量，绝不用于用户输入。 */
    public static ${F}<${v.java}> lit(${v.java} value) { return ${F}.of(literal(value)); }`);
    m.push(`    /** CASE WHEN condition THEN result ...，结果是 {@code ${F}}。 */
    public static Case<${v.java}, ${F}<${v.java}>> caseWhen(Runnable condition, ${v.java} result) { return Case.start(condition, param(result), ${F}::of); }`);
  }
  return `${header}package ${ROOT};

import ${ROOT}.expr.Case;
import ${ROOT}.expr.Expr;
import ${ROOT}.expr.Family;
import ${ROOT}.expr.Nodes;
${exprImports(JAVA_VALUES.map((v) => v.of)).join("\n")}
import ${ROOT}.select.Rows;
import ${ROOT}.type.SqlType;

${javaImports(JAVA_VALUES.map((v) => v.java)).join("\n")}
import java.util.Objects;

/**
 * 按值的 Java 类给出结果类型的 {@code val}、{@code lit}、{@code caseWhen}：{@code val("x").upper()}、
 * {@code caseWhen(() -> ..., BigDecimal.ONE).otherwise(BigDecimal.ZERO).times(l.quantity())} 都能接着写。
 * 通过 {@link Sql} 和各方言门面使用，不必直接引用本类。
 */
public abstract class SqlValues extends Rows {
    /** 只供 {@link Sql} 继承。 */
    protected SqlValues() { }

    /** 绑定参数，类型由值的类决定；在 SELECT 列表等位置会写成字面量。默认用它。 */
    public static <T> Expr<T> val(T value) { return param(value); }

    /** 写进 SQL 文本的字面量；只用于代码里的固定常量，绝不用于用户输入。 */
    public static <T> Expr<T> lit(T value) { return literal(value); }

    /** CASE WHEN condition THEN result ...，结果与 result 同一类型；再接 .when(...)，以 .otherwise(...) 或 .end() 结束。 */
    public static <T, F extends Expr<T>> Case<T, F> caseWhen(Runnable condition, Family<T, F> result) { return Case.start(condition, result, result::retype); }

    /** 同上，result 没有专门的类型接口时结果是 {@code Expr<T>}。 */
    public static <T> Case<T, Expr<T>> caseWhen(Runnable condition, Expr<T> result) { return Case.start(condition, result, e -> e); }

    /** 同上，结果是常量值，类型取自值的类。 */
    public static <T> Case<T, Expr<T>> caseWhen(Runnable condition, T result) { return Case.start(condition, param(result), e -> e); }

${m.join("\n\n")}

    /** 按值的类绑定的参数。 */
    @SuppressWarnings("unchecked")
    private static <T> Expr<T> param(T value) {
        Objects.requireNonNull(value, "value; use nullOf(Type.class) for NULL");
        return new Nodes.Param<>((SqlType<T>) SqlType.of(value.getClass()), value);
    }

    /** 按值的类写出的字面量。 */
    @SuppressWarnings("unchecked")
    private static <T> Expr<T> literal(T value) {
        Objects.requireNonNull(value, "value; use nullOf(Type.class) for NULL");
        return new Nodes.Literal<>((SqlType<T>) SqlType.of(value.getClass()), value);
    }
}
`;
}

/** 简单 CASE 的第一个分支：它决定结果的类型。 */
function caseOf() {
  const m = JAVA_VALUES.map((v) => `    /** 第一个分支：subject 等于 value 时取常量 result，结果是 {@code Expr${v.of}}。 */
    public Case.Simple<V, ${v.java}, Expr${v.of}<${v.java}>> when(V value, ${v.java} result) { return Case.Simple.start(subject, value, param(result), Expr${v.of}::of); }`);
  return `${header}package ${ROOT}.expr;

${exprImports(JAVA_VALUES.map((v) => v.of)).join("\n")}
import ${ROOT}.type.SqlType;

${javaImports(JAVA_VALUES.map((v) => v.java)).join("\n")}
import java.util.Objects;

/**
 * 简单 CASE 的开头，由 {@code caseOf(subject)} 创建：{@code caseOf(code).when("1", "自有").when("2", "供应商").otherwise("其他")}。
 * 第一个分支的结果决定整个 CASE 的类型。
 *
 * @param <V> 比较对象的类型
 */
public final class CaseOf<V> {
    /** 被比较的表达式。 */
    private final Expr<V> subject;

    /** 由 {@code caseOf} 创建。 */
    public CaseOf(Expr<V> subject) { this.subject = Objects.requireNonNull(subject, "subject"); }

    /** 第一个分支：subject 等于 value 时取表达式 result，结果与 result 同一类型。 */
    public <T, F extends Expr<T>> Case.Simple<V, T, F> when(V value, Family<T, F> result) { return Case.Simple.start(subject, value, result, result::retype); }

    /** 同上，result 没有专门的类型接口时结果是 {@code Expr<T>}。 */
    public <T> Case.Simple<V, T, Expr<T>> when(V value, Expr<T> result) { return Case.Simple.start(subject, value, result, e -> e); }

    /** 第一个分支：subject 等于 value 时取常量 result，类型取自 result 的类。 */
    public <T> Case.Simple<V, T, Expr<T>> when(V value, T result) { return Case.Simple.start(subject, value, param(result), e -> e); }

${m.join("\n\n")}

    /** 按值的类绑定的参数。 */
    @SuppressWarnings("unchecked")
    private static <T> Expr<T> param(T value) {
        Objects.requireNonNull(value, "result; use nullOf(Type.class) for NULL");
        return new Nodes.Param<>((SqlType<T>) SqlType.of(value.getClass()), value);
    }
}
`;
}

/** getter 引用，按属性的类型分出子接口，供 {@code r.col(Row::x)} 按 getter 的返回类型选出列接口。 */
function getter() {
  const nested = JAVA_VALUES.map((v) => `    /** 返回 ${v.java} 的 getter；{@code r.col(...)} 收到它时得到 {@code Col${v.of}}。 */
    @FunctionalInterface
    interface Of${v.getter}<E> extends Getter<E, ${v.java}> { }`);
  return `${header}package ${ROOT}.meta;

import java.io.Serializable;
${javaImports(JAVA_VALUES.map((v) => v.java)).join("\n")}

/**
 * 对 getter 或 record 访问器的引用，例如 {@code Lips::getMaterial}、{@code Material::partNumber}。
 * 它可序列化，因此能还原出被引用方法的名字；不是方法引用的 lambda 会被拒绝。
 * 按返回类型分的子接口（{@link OfString} 等）让 {@code r.col(Row::name)} 直接得到 {@code ColText<String>}。
 *
 * @param <E> 行类型
 * @param <T> 属性值类型
 */
@FunctionalInterface
public interface Getter<E, T> extends Serializable {
    /** 读取一行的属性值；元数据只用它的方法名，不会真正调用。 */
    T get(E row);

${nested.join("\n\n")}
}
`;
}

/** Ref 按 getter 的返回类型给出列接口的 col(...) 重载。 */
function refColumns() {
  const m = JAVA_VALUES.map((v) => `    /** CTE、派生表或常量行里返回 ${v.java} 的属性所对应的列。 */
    public Col${v.of}<${v.java}> col(Getter.Of${v.getter}<? super E> getter) { return typed(getter, Col${v.of}.class); }`);
  return `${header}package ${ROOT}.table;

import ${ROOT}.meta.Getter;
import ${ROOT}.table.column.Col;
${[...new Set(JAVA_VALUES.map((v) => v.of))].map((n) => `import ${ROOT}.table.column.Col${n};`).sort().join("\n")}

${javaImports(JAVA_VALUES.map((v) => v.java)).join("\n")}

/**
 * {@link Ref} 的 {@code col(...)}：按 getter 的返回类型选出列接口，{@code r.col(Row::name)} 是 {@code ColText<String>}，
 * {@code r.col(Row::total)} 是 {@code ColDecimal<BigDecimal>}；其余类型（枚举等）得到 {@code Col<T>}。只限方法引用。
 *
 * @param <E> 行类型
 */
abstract class RefColumns<E> {
    /** 只供 {@link Ref} 继承。 */
    RefColumns() { }

    /** 属性 getter 对应的列。 */
    abstract Col<?> column(Getter<? super E, ?> getter);

    /** CTE、派生表或常量行的一列；{@code ? super E} 允许传入基类和接口上的 getter。表的列直接用表接口的方法，调用本方法会报错。 */
    @SuppressWarnings("unchecked")
    public <T> Col<T> col(Getter<? super E, T> getter) { return (Col<T>) column(getter); }

${m.join("\n\n")}

    /** 列按库里的存储类型得到的接口要与 getter 的返回类型一致；经转换器存成别的类型时报错。 */
    @SuppressWarnings("unchecked")
    private <C> C typed(Getter<? super E, ?> getter, Class<C> expected) {
        Col<?> column = column(getter);
        if (expected.isInstance(column)) return (C) column;
        throw new IllegalArgumentException(column + " is stored as " + column.type().storageType().getSimpleName()
            + "; take it as Col<T> with r.col((Getter<Row, T>) Row::property) and wrap it, e.g. ExprText.of(...)");
    }
}
`;
}

// ---------- 函数接口、按位置投影、作用域 ----------

function fn() {
  const functions = range(Math.max(MAX_TABLES, MAX_ROW)).map((k) => {
    const args = range(k).map((i) => `T${i} t${i}`).join(", ");
    return `    /** ${k} 个参数的函数。 */
    @FunctionalInterface
    public interface F${k}<${types(k).join(", ")}, R> {
        R apply(${args});
    }`;
  });
  const blocks = range(MAX_TABLES + 1).map((k) => {
    const args = range(k).map((i) => `T${i} t${i}`).join(", ");
    return `    /** ${k} 个参数、不返回值的语句块，例如作用域的 where 与连接的 on。 */
    @FunctionalInterface
    public interface C${k}<${types(k).join(", ")}> {
        void accept(${args});
    }`;
  });
  return `${header}package ${ROOT};

/** 作用域 lambda 与 row(...) 构造器引用使用的函数接口，按参数个数编号：F 有返回值，C 是不返回值的语句块。 */
public final class Fn {
    /** 只放函数式接口，不能实例化。 */
    private Fn() { }

${functions.join("\n\n")}

${blocks.join("\n\n")}
}
`;
}

function rows() {
  const methods = range(MAX_ROW).map((k) => {
    const tp = types(k);
    const args = range(k).map((i) => `Selection<T${i}> c${i}`).join(", ");
    const casts = range(k).map((i) => `(T${i}) a[${i - 1}]`).join(", ");
    const parts = range(k).map((i) => `c${i}`).join(", ");
    return `    /** 用 ${k} 个参数的构造器按位置组装结果。 */
    @SuppressWarnings("unchecked")
    public static <${tp.join(", ")}, R> RowSelection<R> row(Fn.F${k}<${tp.join(", ")}, R> constructor, ${args}) {
        return new RowSelection<>(a -> constructor.apply(${casts}), ${parts});
    }`;
  });
  return `${header}package ${ROOT}.select;

import ${ROOT}.Fn;

/**
 * 按位置投影：{@code row(Delivery::new, l.material(), l.quantity().sum())}。每个参数是一列、嵌套的
 * {@code row(...)} 或 {@code cols(...)}，javac 逐位检查它的类型与构造器参数是否一致。
 * 通过 {@link ${ROOT}.Sql} 和各方言门面使用，不必直接引用本类。
 */
public abstract class Rows {
    /** 只供 {@link ${ROOT}.Sql} 继承。 */
    protected Rows() { }

${methods.join("\n\n")}
}
`;
}

function from(n) {
  const tp = types(n);
  const self = `From${n}<${tp.join(", ")}>`;
  const names = params(n);
  const call = names.join(", ");
  const fields = tp.map((t, i) => `    private final ${t} ${names[i]};`).join("\n");
  const ctorArgs = tp.map((t, i) => `${t} ${names[i]}`).join(", ");
  const assigns = names.map((p) => `        this.${p} = ${p};`).join("\n");
  const lam = (ret) => `Fn.F${n}<${tp.join(", ")}, ${ret}>`;
  const block = `Fn.C${n}<${tp.join(", ")}>`;
  const m = [];

  if (n === 1) {
    m.push(`    /** 以一个来源开始作用域；p1 是表接口，或 CTE 等来源的 Ref。 */
    public static <T1> From1<T1> start(Ref<?> ref, T1 p1) { return new From1<>(SelectSpec.from(ref), p1); }`);
  }
  m.push(`    /** 换一份 SELECT 内容，各表的参数不变。 */
    @Override ${self} rebuild(SelectSpec spec) { return new From${n}<>(spec, ${call}); }`);

  if (n < MAX_TABLES) {
    const next = `From${n + 1}`;
    const on = (p) => `Fn.C${n + 1}<${tp.join(", ")}, ${p}>`;
    for (const [method, kind, what] of [
      ["join", "INNER", "INNER JOIN"],
      ["leftJoin", "LEFT", "LEFT JOIN"],
      ["rightJoin", "RIGHT", "RIGHT JOIN"],
      ["fullJoin", "FULL", "FULL JOIN（HANA、PostgreSQL；有全局过滤条件的表不能参与）"],
    ]) {
      m.push(`    /** ${what} 一张表；新表是 lambda 的下一个参数，on 里写连接条件，可以用到作用域内所有的表。 */
    public <N extends Entity> ${next}<${tp.join(", ")}, N> ${method}(Class<N> table, ${on("N")} on) { return next(SelectSpec.JoinKind.${kind}, Ref.table(table), on); }`);
      m.push(`    /** ${what} 一个 CTE、派生表或常量行；lambda 的下一个参数是它的 Ref，用 {@code r.col(Row::x)} 取列。 */
    public <E> ${next}<${tp.join(", ")}, Ref<E>> ${method}(Source<E> source, ${on("Ref<E>")} on) { return next(SelectSpec.JoinKind.${kind}, Ref.of(source), on); }`);
    }
    m.push(`    /** CROSS JOIN 一张表（笛卡尔积）。 */
    public <N extends Entity> ${next}<${tp.join(", ")}, N> crossJoin(Class<N> table) { return next(SelectSpec.JoinKind.CROSS, Ref.table(table), null); }`);
    m.push(`    /** CROSS JOIN 一个 CTE、派生表或常量行，例如码表。 */
    public <E> ${next}<${tp.join(", ")}, Ref<E>> crossJoin(Source<E> source) { return next(SelectSpec.JoinKind.CROSS, Ref.of(source), null); }`);
    m.push(`    /** 连接 ref 后的作用域：先运行 on 收集连接条件（skipEmpty 下省略空值条件），新表成为最后一个参数。 */
    private <N> ${next}<${tp.join(", ")}, N> next(SelectSpec.JoinKind kind, Ref<?> ref, ${on("N")} on) {
        N param = ref.param();
        Cond condition = on == null ? null : condition(() -> on.accept(${call}, param));
        return new ${next}<>(spec.join(kind, ref, condition), ${call}, param);
    }`);
  }

  m.push(`    /** WHERE 条件，一行写一个：{@code where(l -> { l.unit().eq("KG"); l.quantity().gt(x); })}；多次调用之间也是 AND。 */
    public ${self} where(${block} cond) { return rebuild(spec.where(condition(() -> cond.accept(${call})))); }`);
  m.push(`    /** 分组：一个键直接写表达式，多个键写 keys(a, b)。 */
    public ${self} groupBy(${lam("? extends Keys")} keys) { return rebuild(spec.groupBy(KeyList.of(Conditions.outside(() -> keys.apply(${call}))))); }`);
  m.push(`    /** GROUP BY ROLLUP：一次列出全部分组键，按每个前缀出小计，最后出总计。 */
    public ${self} groupByRollup(${lam("? extends Keys")} keys) { return rebuild(spec.groupByRollup(KeyList.of(Conditions.outside(() -> keys.apply(${call}))))); }`);
  m.push(`    /** HAVING 条件，写法同 where；多次调用之间是 AND。 */
    public ${self} having(${block} cond) { return rebuild(spec.having(condition(() -> cond.accept(${call})))); }`);
  m.push(`    /**
     * 把一对多关系上的集合运算（count、sum、any 等）合成一个按连接键分组的派生表，LEFT JOIN 一次，
     * 代替每个运算一个相关子查询：{@code groupJoin(m -> m.deliveries())}。同一关系上的 where 筛选写成各自聚合的 CASE WHEN。
     */
    public ${self} groupJoin(${lam("Many<?>")} relation) { return rebuild(spec.groupJoin(Conditions.outside(() -> relation.apply(${call})))); }`);
  m.push(`    /**
     * 窗口函数上的条件（QUALIFY），例如每组取最新一行：
     * {@code qualify(l -> rowNumber().over(w -> w.partitionBy(l.material()).orderBy(l.createdOn().desc())).eq(1L))}。
     * 查询会包成派生表，在外层按条件过滤；条件只能用窗口函数，其他条件写在 where 或 having 里。多次调用之间是 AND。
     */
    public ${self} qualify(${block} cond) { return rebuild(spec.qualify(condition(() -> cond.accept(${call})))); }`);
  m.push(`    /** 排序：一个表达式（升序）、asc()/desc()，多项写 orders(a, b.desc())。 */
    public ${self} orderBy(${lam("? extends OrderItem")} order) { return rebuild(spec.orderBy(OrderList.of(Conditions.outside(() -> order.apply(${call}))))); }`);
  m.push(`    /** 需要用到作用域的方言子句，例如 {@code Postgres.distinctOn(...)}。 */
    public ${self} with(${lam("Clause")} clause) { return with(Conditions.outside(() -> clause.apply(${call}))); }`);
  m.push(`    /**
     * 投影。lambda 返回：一个表达式（单列查询）；{@code cols(...)}（按列名，结果是 Map，可再 {@code into(X.class)}）；
     * 或 {@code row(X::new, ...)}（按位置调用构造器，可以嵌套）。投影里要用条件的值时写 {@code bool(() -> ...)}。
     */
    public <R> Query<R> select(${lam("? extends Selection<R>")} selection) { return Query.select(spec, Conditions.outside(() -> selection.apply(${call}))); }`);
  m.push(`    /** 按同名属性从作用域里的表自动取列，映射到 VO；属性名对应不上或对应多张表时报错。 */
    public <V> Query<V> selectAs(Class<V> type) { return Query.auto(spec, type); }`);

  return `${header}package ${ROOT}.scope;

import ${ROOT}.Fn;
import ${ROOT}.dialect.Clause;
import ${ROOT}.expr.Cond;
import ${ROOT}.expr.Conditions;
import ${ROOT}.expr.KeyList;
import ${ROOT}.expr.Keys;
import ${ROOT}.expr.OrderItem;
import ${ROOT}.expr.OrderList;
import ${ROOT}.select.Query;
import ${ROOT}.select.SelectSpec;
import ${ROOT}.select.Selection;
import ${ROOT}.table.Entity;
import ${ROOT}.table.Many;
import ${ROOT}.table.Ref;
import ${ROOT}.table.Source;

/** ${n} 个来源的作用域：每个来源是 lambda 的一个参数，表是表接口本身，CTE 等来源是 Ref。 */
public final class ${self} extends AbstractFrom<${self}> {
${fields}

    From${n}(SelectSpec spec, ${ctorArgs}) {
        super(spec);
${assigns}
    }

${m.join("\n\n")}
}
`;
}

