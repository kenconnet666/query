  m.push(`    /** 保留 scale 位小数四舍五入。 */
    @Override default ${F}<${J}> round(int scale) { return ${own("ROUND", ", Nodes.literal(Integer.class, scale)")}; }`);
  m.push(`    /** 取负：{@code -(this)}。 */
    @Override default ${F}<${J}> negate() { return ${F}.of(new Nodes.Negated<>(Stored.type(this, ${J}.class), this)); }`);
