/** 外壳：把任意节点包成某一类型的表达式。 */
function shells() {
  const classes = FAMILIES.map((t) => `    /** ${t.what}的外壳。 */
    static final class Of${t.name}<T> extends Shell<T> implements Expr${t.name}<T> {
        Of${t.name}(Expr<T> node) { super(node); }
    }`);
  return `${header}package ${ROOT}.expr.typed;

import ${ROOT}.dialect.SqlWriter;
import ${ROOT}.expr.Expr;
import ${ROOT}.expr.ExprNode;

/**
 * 把任意节点包成某一类型的表达式（{@code ExprText.of(node)} 等）：类型接口的方法都是 default 方法，外壳只把渲染和列名交给被包的节点。
 * 渲染经由 {@code w.render(node)}，所以渲染器按节点做的替换（QUALIFY 的窗口函数、groupJoin 的聚合）照样认得出被包的节点。
 * 外部只用 {@link #unwrap}（经由 {@code Nodes.unwrap}）。
 */
public final class Shells {
    /** 只放外壳类，不能实例化。 */
    private Shells() { }

    /** 外壳的公共部分；被包的节点不会是外壳，套娃时先拆开。 */
    abstract static class Shell<T> extends ExprNode<T> {
        /** 被包的节点。 */
        final Expr<T> node;

        Shell(Expr<T> node) {
            super(node.type());
            this.node = unwrap(node);
        }

        /** 交给被包的节点渲染。 */
        @Override public void render(SqlWriter w) { w.render(node); }

        /** 沿用被包节点的列名。 */
        @Override public String label() { return node.label(); }

        /** 沿用被包节点的名字提示。 */
        @Override public String nameHint() { return node.nameHint(); }

        /** 调试用，与被包的节点相同。 */
        @Override public String toString() { return node.toString(); }
    }

    /** 拆掉外壳，得到真正的节点；不是外壳时原样返回。 */
    public static <T> Expr<T> unwrap(Expr<T> e) { return e instanceof Shell<T> s ? s.node : e; }

${classes.join("\n\n")}
}
`;
}

