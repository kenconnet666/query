/** 列的实现：每种类型一个类，按库里的存储类型选用。 */
function columns() {
  const lobOf = (t) => LOBS.find((l) => l.of === t.name);
  const classes = FAMILIES.map((t) => {
    const lob = lobOf(t);
    return `    /** ${t.what}列${lob ? `，也是 {@link Col${lob.name}}` : ""}。 */
    static final class Of${t.name}<T> extends ColumnNode<T> implements Col${t.name}<T>${lob ? `, Col${lob.name}<T>` : ""} {
        Of${t.name}(Ref<?> ref, PropertyMeta property) { super(ref, property); }
    }`;
  });
  const creates = FAMILIES.map((t) => `        if (${t.stored.map((s) => `stored == ${s}.class`).join(" || ")}) return new Of${t.name}<>(ref, property);`);
  const declared = FAMILIES.map((t) => `        if (${t.stored.map((s) => `stored == ${s}.class`).join(" || ")}) return Col${t.name}.class;`);
  const allows = LOBS.map((l) => `        if (declared == Col${l.name}.class) return expected == Col${l.of}.class;`);
  return `${header}package ${ROOT}.table.column;

import ${ROOT}.meta.PropertyMeta;
import ${ROOT}.table.Ref;

${javaImports(FAMILIES.flatMap((t) => t.stored)).join("\n")}

/** 列的实现。类型接口的方法都是 default 方法，所以每种类型只是一个空类；没有专门接口的存储类型用 {@link Any}。 */
final class Columns {
    /** 只放列的实现，不能实例化。 */
    private Columns() { }

    /** ref 里的一列，按库里的存储类型选择实现。 */
    static Col<?> create(Ref<?> ref, PropertyMeta property) {
        Class<?> stored = property.type().storageType();
${creates.join("\n")}
        return new Any<>(ref, property);
    }

    /** 存储类型为 stored 的列在表接口里应当声明的接口，例如 String 是 {@link ColText}；没有专门接口时是 {@link Col}。 */
    static Class<?> declared(Class<?> stored) {
${declared.join("\n")}
        return Col.class;
    }

    /** 存储类型为 stored 的列能不能声明成 declared：除了 {@link #declared} 给出的接口，文本还可以是 ColClob，字节串还可以是 ColBlob。 */
    static boolean allows(Class<?> declared, Class<?> stored) {
        Class<?> expected = declared(stored);
${allows.join("\n")}
        return declared == expected;
    }

    /** 没有专门接口的存储类型（JSON、数组、UUID 等）的列。 */
    static final class Any<T> extends ColumnNode<T> {
        Any(Ref<?> ref, PropertyMeta property) { super(ref, property); }
    }

${classes.join("\n\n")}
}
`;
}

