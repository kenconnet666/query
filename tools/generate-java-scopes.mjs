// 生成 query-core 里随参数个数变化的代码：作用域 From1..From16、函数接口 Fn.F1..F22、按位置投影 Rows.row(...)。
// 在仓库根目录运行：node tools/generate-java-scopes.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const MAX_TABLES = 16; // 一个作用域最多连接的表数
const MAX_ROW = 22; // row(X::new, ...) 最多的构造器参数个数
const dir = "java/query-core/src/main/java/org/dpdns/zerodep/query";
const ROOT = "org.dpdns.zerodep.query";
const header = "// Generated by tools/generate-java-scopes.mjs; edit the generator, not this file.\n";

const range = (n) => Array.from({ length: n }, (_, i) => i + 1);
const types = (n) => range(n).map((i) => `T${i}`);
const params = (n) => range(n).map((i) => `p${i}`);

function fn() {
  const lines = range(Math.max(MAX_TABLES, MAX_ROW)).map((k) => {
    const args = range(k).map((i) => `T${i} t${i}`).join(", ");
    return `    /** ${k} 个参数的函数。 */
    @FunctionalInterface
    public interface F${k}<${types(k).join(", ")}, R> {
        R apply(${args});
    }`;
  });
  return `${header}package ${ROOT};

/** 作用域 lambda 与 row(...) 构造器引用使用的函数接口，按参数个数编号。 */
public final class Fn {
    /** 只放函数式接口，不能实例化。 */
    private Fn() { }

${lines.join("\n\n")}
}
`;
}

function rows() {
  const methods = range(MAX_ROW).map((k) => {
    const tp = types(k);
    const args = range(k).map((i) => `Selection<T${i}> c${i}`).join(", ");
    const casts = range(k).map((i) => `(T${i}) a[${i - 1}]`).join(", ");
    const parts = range(k).map((i) => `c${i}`).join(", ");
    return `    /** 用 ${k} 个参数的构造器按位置组装结果。 */
    @SuppressWarnings("unchecked")
    public static <${tp.join(", ")}, R> RowSelection<R> row(Fn.F${k}<${tp.join(", ")}, R> constructor, ${args}) {
        return new RowSelection<>(a -> constructor.apply(${casts}), ${parts});
    }`;
  });
  return `${header}package ${ROOT}.select;

import ${ROOT}.Fn;

/**
 * 按位置投影：{@code row(Delivery::new, l.material(), sum(l.quantity()))}。每个参数是一列、嵌套的
 * {@code row(...)} 或 {@code cols(...)}，javac 逐位检查它的类型与构造器参数是否一致。
 * 通过 {@link ${ROOT}.Sql} 和各方言门面使用，不必直接引用本类。
 */
public abstract class Rows {
    /** 只供 {@link ${ROOT}.Sql} 继承。 */
    protected Rows() { }

${methods.join("\n\n")}
}
`;
}

function from(n) {
  const tp = types(n);
  const self = `From${n}<${tp.join(", ")}>`;
  const names = params(n);
  const call = names.join(", ");
  const fields = tp.map((t, i) => `    private final ${t} ${names[i]};`).join("\n");
  const ctorArgs = tp.map((t, i) => `${t} ${names[i]}`).join(", ");
  const assigns = names.map((p) => `        this.${p} = ${p};`).join("\n");
  const lam = (ret) => `Fn.F${n}<${tp.join(", ")}, ${ret}>`;
  const m = [];

  if (n === 1) {
    m.push(`    /** 以一个来源开始作用域；p1 是表接口，或 CTE 等来源的 Ref。 */
    public static <T1> From1<T1> start(Ref<?> ref, T1 p1) { return new From1<>(SelectSpec.from(ref), p1); }`);
  }
  m.push(`    /** 换一份 SELECT 内容，各表的参数不变。 */
    @Override ${self} rebuild(SelectSpec spec) { return new From${n}<>(spec, ${call}); }`);

  if (n < MAX_TABLES) {
    const next = `From${n + 1}`;
    const on = (p) => `Fn.F${n + 1}<${tp.join(", ")}, ${p}, Cond>`;
    for (const [method, kind, what] of [
      ["join", "INNER", "INNER JOIN"],
      ["leftJoin", "LEFT", "LEFT JOIN"],
    ]) {
      m.push(`    /** ${what} 一张表；新表是 lambda 的下一个参数，on 里可以用到作用域内所有的表。 */
    public <N extends Entity> ${next}<${tp.join(", ")}, N> ${method}(Class<N> table, ${on("N")} on) { return next(SelectSpec.JoinKind.${kind}, Ref.table(table), on); }`);
      m.push(`    /** ${what} 一个 CTE、派生表或常量行；lambda 的下一个参数是它的 Ref，用 {@code r.col(Row::x)} 取列。 */
    public <E> ${next}<${tp.join(", ")}, Ref<E>> ${method}(Source<E> source, ${on("Ref<E>")} on) { return next(SelectSpec.JoinKind.${kind}, Ref.of(source), on); }`);
    }
    m.push(`    /** CROSS JOIN 一张表（笛卡尔积）。 */
    public <N extends Entity> ${next}<${tp.join(", ")}, N> crossJoin(Class<N> table) { return next(SelectSpec.JoinKind.CROSS, Ref.table(table), null); }`);
    m.push(`    /** CROSS JOIN 一个 CTE、派生表或常量行，例如码表。 */
    public <E> ${next}<${tp.join(", ")}, Ref<E>> crossJoin(Source<E> source) { return next(SelectSpec.JoinKind.CROSS, Ref.of(source), null); }`);
    m.push(`    /** 连接 ref 后的作用域：先用 on 构造连接条件（skipEmpty 下省略空值条件），新表成为最后一个参数。 */
    private <N> ${next}<${tp.join(", ")}, N> next(SelectSpec.JoinKind kind, Ref<?> ref, ${on("N")} on) {
        N param = ref.param();
        Cond condition = on == null ? null : condition(() -> on.apply(${call}, param));
        return new ${next}<>(spec.join(kind, ref, condition), ${call}, param);
    }`);
  }

  m.push(`    /** WHERE 条件；多次调用之间是 AND，值为空而省略的条件（Cond.EMPTY）会被丢弃。 */
    public ${self} where(${lam("Cond")} cond) { return rebuild(spec.where(condition(() -> cond.apply(${call})))); }`);
  m.push(`    /** 分组：一个键直接写表达式，多个键写 keys(a, b)。 */
    public ${self} groupBy(${lam("? extends Keys")} keys) { return rebuild(spec.groupBy(KeyList.of(keys.apply(${call})))); }`);
  m.push(`    /** GROUP BY ROLLUP：一次列出全部分组键，按每个前缀出小计，最后出总计。 */
    public ${self} groupByRollup(${lam("? extends Keys")} keys) { return rebuild(spec.groupByRollup(KeyList.of(keys.apply(${call})))); }`);
  m.push(`    /** HAVING 条件；多次调用之间是 AND。 */
    public ${self} having(${lam("Cond")} cond) { return rebuild(spec.having(condition(() -> cond.apply(${call})))); }`);
  m.push(`    /**
     * 窗口函数上的条件（QUALIFY），例如每组取最新一行：
     * {@code qualify(l -> rowNumber().over(w -> w.partitionBy(l.material()).orderBy(l.createdOn().desc())).eq(1L))}。
     * 查询会包成派生表，在外层按条件过滤；条件只能用窗口函数，其他条件写在 where 或 having 里。多次调用之间是 AND。
     */
    public ${self} qualify(${lam("Cond")} cond) { return rebuild(spec.qualify(condition(() -> cond.apply(${call})))); }`);
  m.push(`    /** 排序：一个表达式（升序）、asc()/desc()，多项写 orders(a, b.desc())。 */
    public ${self} orderBy(${lam("? extends OrderItem")} order) { return rebuild(spec.orderBy(OrderList.of(order.apply(${call})))); }`);
  m.push(`    /** 需要用到作用域的方言子句，例如 {@code Postgres.distinctOn(...)}。 */
    public ${self} with(${lam("Clause")} clause) { return with(clause.apply(${call})); }`);
  m.push(`    /**
     * 投影。lambda 返回：一个表达式（单列查询）；{@code cols(...)}（按列名，结果是 Map，可再 {@code into(X.class)}）；
     * 或 {@code row(X::new, ...)}（按位置调用构造器，可以嵌套）。
     */
    public <R> Query<R> select(${lam("? extends Selection<R>")} selection) { return Query.select(spec, selection.apply(${call})); }`);
  m.push(`    /** 按同名属性从作用域里的表自动取列，映射到 VO；属性名对应不上或对应多张表时报错。 */
    public <V> Query<V> selectAs(Class<V> type) { return Query.auto(spec, type); }`);

  return `${header}package ${ROOT}.scope;

import ${ROOT}.Fn;
import ${ROOT}.dialect.Clause;
import ${ROOT}.expr.Cond;
import ${ROOT}.expr.KeyList;
import ${ROOT}.expr.Keys;
import ${ROOT}.expr.OrderItem;
import ${ROOT}.expr.OrderList;
import ${ROOT}.select.Query;
import ${ROOT}.select.SelectSpec;
import ${ROOT}.select.Selection;
import ${ROOT}.table.Entity;
import ${ROOT}.table.Ref;
import ${ROOT}.table.Source;

/** ${n} 个来源的作用域：每个来源是 lambda 的一个参数，表是表接口本身，CTE 等来源是 Ref。 */
public final class ${self} extends AbstractFrom<${self}> {
${fields}

    From${n}(SelectSpec spec, ${ctorArgs}) {
        super(spec);
${assigns}
    }

${m.join("\n\n")}
}
`;
}

writeFileSync(join(dir, "Fn.java"), fn());
writeFileSync(join(dir, "select", "Rows.java"), rows());
for (let n = 1; n <= MAX_TABLES; n++) writeFileSync(join(dir, "scope", `From${n}.java`), from(n));
console.log(`Generated Fn.java, Rows.java and From1..From${MAX_TABLES}.java in ${dir}`);
