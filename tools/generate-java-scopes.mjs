// Generates the lambda scopes From1..From8 and the functional interfaces Fn.F1..F9 of query-core.
// Run from the repository root: node tools/generate-java-scopes.mjs
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const MAX = 8;
const dir = "java/query-core/src/main/java/org/dpdns/zerodep/query";
const letters = "ABCDEFGHI".split("");
const header = "// Generated by tools/generate-java-scopes.mjs; edit the generator, not this file.\n";

const types = (n) => letters.slice(0, n);
const refs = (n) => types(n).map((t) => `Ref<${t}>`);
const params = (n) => types(n).map((t) => t.toLowerCase());

function fn() {
  const lines = [];
  for (let k = 1; k <= MAX + 1; k++) {
    const tp = types(k);
    const args = tp.map((t) => `${t} ${t.toLowerCase()}`).join(", ");
    lines.push(`    @FunctionalInterface\n    public interface F${k}<${tp.join(", ")}, R> {\n        R apply(${args});\n    }`);
  }
  return `${header}package org.dpdns.zerodep.query;

/** Functional interfaces for scope lambdas; F(n+1) takes a Row plus n refs. */
public final class Fn {
    private Fn() { }

${lines.join("\n\n")}
}
`;
}

function from(n) {
  const tp = types(n);
  const self = `From${n}<${tp.join(", ")}>`;
  const scope = refs(n).join(", ");
  const names = params(n);
  const call = names.join(", ");
  const fields = tp.map((t, i) => `    private final Ref<${t}> ${names[i]};`).join("\n");
  const ctorArgs = tp.map((t, i) => `Ref<${t}> ${names[i]}`).join(", ");
  const assigns = names.map((p) => `        this.${p} = ${p};`).join("\n");
  const m = [];

  if (n === 1) {
    m.push(`    static <A> From1<A> start(Ref<A> a) { return new From1<>(SelectSpec.from(a), a); }`);
  }
  m.push(`    @Override ${self} rebuild(SelectSpec spec) { return new From${n}<>(spec, ${call}); }`);

  if (n < MAX) {
    const next = letters[n];
    const nextSelf = `From${n + 1}<${[...tp, next].join(", ")}>`;
    const onType = `Fn.F${n + 1}<${[...refs(n), `Ref<${next}>`].join(", ")}, Cond>`;
    const nextName = next.toLowerCase();
    for (const [method, kind, doc] of [
      ["join", "INNER", "INNER JOIN; the new table is the next lambda parameter."],
      ["leftJoin", "LEFT", "LEFT JOIN; the new table is the next lambda parameter."],
    ]) {
      m.push(`    /** ${doc} */
    public <${next}> ${nextSelf} ${method}(Class<${next}> entity, ${onType} on) { return join(SelectSpec.JoinKind.${kind}, ref(entity), on); }`);
      m.push(`    public <${next}> ${nextSelf} ${method}(Source<${next}> source, ${onType} on) { return join(SelectSpec.JoinKind.${kind}, ref(source), on); }`);
    }
    m.push(`    public <${next}> ${nextSelf} crossJoin(Class<${next}> entity) { return join(SelectSpec.JoinKind.CROSS, ref(entity), null); }`);
    m.push(`    public <${next}> ${nextSelf} crossJoin(Source<${next}> source) { return join(SelectSpec.JoinKind.CROSS, ref(source), null); }`);
    m.push(`    private <${next}> ${nextSelf} join(SelectSpec.JoinKind kind, Ref<${next}> ${nextName}, ${onType} on) {
        Cond condition = on == null ? null : on.apply(${call}, ${nextName});
        return new From${n + 1}<>(spec.join(kind, ${nextName}, condition), ${call}, ${nextName});
    }`);
  }

  const lam = (ret) => `Fn.F${n}<${scope}, ${ret}>`;
  m.push(`    public ${self} where(${lam("Cond")} cond) { return rebuild(spec.where(cond.apply(${call}))); }`);
  m.push(`    public ${self} whereIf(boolean test, ${lam("Cond")} cond) { return test ? where(cond) : this; }`);
  m.push(`    public ${self} groupBy(${lam("List<? extends Expr<?>>")} keys) { return rebuild(spec.groupBy(keys.apply(${call}))); }`);
  m.push(`    public ${self} having(${lam("Cond")} cond) { return rebuild(spec.having(cond.apply(${call}))); }`);
  m.push(`    public ${self} orderBy(${lam("List<Order>")} orders) { return rebuild(spec.orderBy(orders.apply(${call}))); }`);
  m.push(`    /** A dialect clause that needs the scope, e.g. {@code Postgres.distinctOn(...)}. */
    public ${self} with(${lam("Clause")} clause) { return with(clause.apply(${call})); }`);
  m.push(`    /** Functional projection: build any result object from values read through the row. */
    public <R> Query<R> select(Fn.F${n + 1}<Row, ${scope}, R> projection) { return Query.functional(spec, row -> projection.apply(row, ${call})); }`);
  m.push(`    /** Named projection: every property of the shape from the same-named property of one source, or its @MapFrom. */
    public <V> Query<V> selectAs(Class<V> shape) { return Query.auto(spec, shape); }`);
  m.push(`    /** Named projection with explicit columns, each labeled with .as(Shape::getX) or by its property name. */
    public <V> Query<V> selectAs(Class<V> shape, ${lam("List<? extends Expr<?>>")} columns) { return Query.named(spec, shape, columns.apply(${call})); }`);
  m.push(`    /** One column: a scalar or IN subquery, or a list of single values. */
    public <T> Query<T> selectValue(${lam("Expr<T>")} value) { return Query.value(spec, value.apply(${call})); }`);

  return `${header}package org.dpdns.zerodep.query;

import org.dpdns.zerodep.query.dialect.Clause;

import java.util.List;

/** A scope of ${n} table${n > 1 ? "s" : ""}; each is a typed lambda parameter. */
public final class ${self} extends AbstractFrom<${self}> {
${fields}

    From${n}(SelectSpec spec, ${ctorArgs}) {
        super(spec);
${assigns}
    }

${m.join("\n\n")}
}
`;
}

writeFileSync(join(dir, "Fn.java"), fn());
for (let n = 1; n <= MAX; n++) writeFileSync(join(dir, `From${n}.java`), from(n));
console.log(`Generated Fn.java and From1..From${MAX}.java in ${dir}`);
