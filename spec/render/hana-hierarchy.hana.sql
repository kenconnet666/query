SELECT HIERARCHY."nodeId" AS "nodeId", HIERARCHY.HIERARCHY_LEVEL AS "hierarchyLevel", HIERARCHY.HIERARCHY_PARENT_RANK AS "hierarchyParentRank", HIERARCHY."name" AS "name"
FROM HIERARCHY(SOURCE (SELECT SRC.*, SRC."nodeId" AS NODE_ID, SRC."parentId" AS PARENT_ID FROM (SELECT ORG.ID AS "nodeId", ORG.PARENT_ID AS "parentId", ORG.NAME AS "name"
FROM QUERY_IT.H_ORG ORG) SRC) SIBLING ORDER BY NODE_ID ASC) HIERARCHY
ORDER BY HIERARCHY.HIERARCHY_RANK ASC
