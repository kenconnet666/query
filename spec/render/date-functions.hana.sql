SELECT EVENT.ID AS "id", YEAR(EVENT.ON_DAY) AS "y", MONTH(EVENT.AT_TIME) AS "m", DAYOFMONTH(EVENT.ON_DAY) AS "d", ADD_DAYS(EVENT.ON_DAY, 3) AS "plusDays", ADD_MONTHS(EVENT.ON_DAY, -1) AS "minusMonth", ADD_YEARS(EVENT.ON_DAY, 1) AS "plusYear", DAYS_BETWEEN(EVENT.ON_DAY, DATE '2024-04-30') AS "days"
FROM QUERY_IT.EVENTS EVENT
WHERE EVENT.ON_DAY >= ? AND EVENT.ON_DAY < ?
ORDER BY EVENT.ID ASC
