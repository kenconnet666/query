SELECT lips."MATNR" AS material, PERCENTILE_CONT(0.5) WITHIN GROUP (ORDER BY CAST(lips."LFIMG" AS DOUBLE PRECISION)) AS median, PERCENTILE_DISC(0.5) WITHIN GROUP (ORDER BY lips."LFIMG") AS lower, MODE() WITHIN GROUP (ORDER BY lips."VRKME") AS unit, CORR(lips."LFIMG", lips."LFIMG") AS self
FROM "QUERY_IT"."LIPS" lips
GROUP BY lips."MATNR"
