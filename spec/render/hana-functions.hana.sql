SELECT DAYS_BETWEEN(DATE '2026-01-01', ADD_DAYS(DATE '2026-01-01', 3)) AS "days", ADD_MONTHS(DATE '2026-01-31', 1) AS "months", ADD_YEARS(DATE '2026-01-31', 2) AS "years", TO_VARCHAR(DATE '2026-01-31', 'YYYYMMDD') AS "text", TO_DATE(LIPS.VBELN, 'YYYYMMDD') AS "day", LENGTH(LIPS.MATNR) AS "size"
FROM QUERY_IT.LIPS LIPS
WITH HINT(NO_CS_JOIN, IGNORE_PLAN_CACHE)
