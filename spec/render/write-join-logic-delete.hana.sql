-- parameters: ["1","0","gone"]
MERGE INTO QUERY_IT.W_TICKET AS TARGET
USING (SELECT TICKET.ID AS "k0", ? AS "v0"
FROM QUERY_IT.W_TICKET TICKET
JOIN QUERY_IT.W_DOC DOC ON TICKET.ID = DOC.ID
WHERE TICKET.DELETED = ? AND DOC.TITLE = ?) AS SOURCE ON (TARGET.ID = SOURCE."k0")
WHEN MATCHED THEN UPDATE SET TARGET.DELETED = SOURCE."v0"
