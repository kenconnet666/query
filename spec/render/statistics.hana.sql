-- parameters: []
SELECT LIPS.MATNR AS "material", SUM(DISTINCT LIPS.LFIMG) AS "distinctTotal", AVG(DISTINCT LIPS.LFIMG) AS "distinctAverage", STDDEV_SAMP(CAST(LIPS.LFIMG AS DOUBLE)) AS "sampleDeviation", STDDEV_POP(CAST(LIPS.LFIMG AS DOUBLE)) AS "populationDeviation", VAR_SAMP(CAST(LIPS.LFIMG AS DOUBLE)) AS "sampleVariance", VAR_POP(CAST(LIPS.LFIMG AS DOUBLE)) AS "populationVariance"
FROM QUERY_IT.LIPS LIPS
GROUP BY LIPS.MATNR
ORDER BY LIPS.MATNR ASC
