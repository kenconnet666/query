SELECT lips.VBELN AS delivery, mara.MFRPN AS partNumber, CASE WHEN lips.LFIMG > 1 THEN TRUE WHEN NOT (lips.LFIMG > 1) THEN FALSE END AS big
FROM QUERY_IT.MARA AS mara
RIGHT JOIN QUERY_IT.LIPS AS lips ON mara.MATNR = lips.MATNR AND mara.MANDT = ?
WHERE lips.MANDT = ? AND (lips.VBELN, lips.MATNR) IN (SELECT lips2.VBELN, lips2.MATNR
FROM QUERY_IT.LIPS AS lips2
WHERE lips2.MANDT = ? AND lips2.VRKME = ?) AND EXISTS (SELECT 1 FROM (SELECT lips3.LFIMG AS quantity
FROM QUERY_IT.LIPS AS lips3
WHERE lips3.MANDT = ? AND lips3.VRKME = ?) AS q WHERE lips.LFIMG >= q.quantity) AND NOT EXISTS (SELECT 1 FROM (SELECT lips4.LFIMG AS quantity
FROM QUERY_IT.LIPS AS lips4
WHERE lips4.MANDT = ? AND lips4.VRKME = ?) AS q2 WHERE (lips.LFIMG < q2.quantity) IS NOT TRUE) AND NOT (mara.MFRNR IS mara.MFRPN) AND lips.VRKME IS NOT mara.MTART
ORDER BY lips.VBELN ASC
