SELECT lips."VBELN" AS delivery, PERCENT_RANK() OVER (ORDER BY lips."LFIMG" ASC) AS "percentRank", CUME_DIST() OVER (PARTITION BY lips."MATNR" ORDER BY lips."LFIMG" ASC) AS "cumeDist", NTH_VALUE(lips."VBELN", 2) OVER (PARTITION BY lips."MATNR" ORDER BY lips."VBELN" ASC ROWS BETWEEN UNBOUNDED PRECEDING AND UNBOUNDED FOLLOWING) AS second
FROM "QUERY_IT"."LIPS" lips
ORDER BY lips."VBELN" ASC
