SELECT HIERARCHY."nodeId" AS "nodeId", HIERARCHY.HIERARCHY_DISTANCE AS "hierarchyDistance"
FROM HIERARCHY_DESCENDANTS(SOURCE HIERARCHY(SOURCE (SELECT SRC.*, SRC."nodeId" AS NODE_ID, SRC."parentId" AS PARENT_ID FROM (SELECT ORG.ID AS "nodeId", ORG.PARENT_ID AS "parentId", ORG.NAME AS "name"
FROM QUERY_IT.H_ORG ORG) SRC) SIBLING ORDER BY NODE_ID ASC) START WHERE NODE_ID IN (?)) HIERARCHY
ORDER BY HIERARCHY."nodeId" ASC
