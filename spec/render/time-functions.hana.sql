SELECT EVENT.ID AS "id", HOUR(EVENT.AT_TIME) AS "h", MINUTE(EVENT.AT_TIME) AS "mi", CAST(FLOOR(SECOND(EVENT.AT_TIME)) AS INTEGER) AS "s", ADD_SECONDS(EVENT.AT_TIME, 90000) AS "plusHours", ADD_SECONDS(EVENT.AT_TIME, -1860) AS "minusMinutes", ADD_SECONDS(EVENT.AT_TIME, 59) AS "plusSeconds", ADD_DAYS(EVENT.ON_DAY, 1 - DAYOFMONTH(EVENT.ON_DAY)) AS "monthStart"
FROM QUERY_IT.EVENTS EVENT
ORDER BY EVENT.ID ASC
