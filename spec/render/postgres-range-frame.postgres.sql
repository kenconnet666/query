SELECT event."ID" AS id, COUNT(*) OVER (ORDER BY event."ON_DAY" ASC RANGE BETWEEN INTERVAL '7 days' PRECEDING AND CURRENT ROW) AS "lastWeek", COUNT(*) OVER (ORDER BY event."ID" ASC RANGE BETWEEN 1 PRECEDING AND 0 FOLLOWING) AS near
FROM "QUERY_IT"."EVENTS" event
ORDER BY event."ID" ASC
