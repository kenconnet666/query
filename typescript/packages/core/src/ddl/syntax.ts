import type { Dialect } from "../sql/dialect.js";
import type { ColumnDef, ColumnType, ForeignKeyDef, IndexDef, TableDef } from "./model.js";

/** 系统目录查询：执行带占位符的 SELECT（方言的占位符写法由 {@link SchemaSyntax.parameter} 给出），每行是小写列标签到值的映射。 */
export type Catalog = (sql: string, ...parameters: unknown[]) => Promise<Record<string, unknown>[]>;

/**
 * 一个方言的结构变更写法：类型名、建表、加列、改列、索引、外键，以及从系统目录读回表的结构。
 * 由方言包实现（`HanaDialect` 的 `schemaSyntax` 等），{@link SchemaTools} 用它比较声明与实库、生成语句；与 Java 端的同名类一致。
 */
export abstract class SchemaSyntax {
  constructor(protected readonly dialect: Dialect) {}

  /** 列类型在本方言里的类型名。 */
  abstract typeName(type: ColumnType): string;

  /** 读取 schema（空串表示连接当前的 schema）里 table 的结构；表不存在时返回 undefined。 */
  abstract read(catalog: Catalog, schema: string, table: string): Promise<TableDef | undefined>;

  /** DDL 是否能在事务里回滚（PostgreSQL 能，MySQL 每条隐式提交，HANA 默认自动提交）。 */
  get transactionalDdl(): boolean {
    return false;
  }

  /** 能否就地改成不是放宽的类型（缩短、改类型族）；HANA 不能。 */
  get changesTypesInPlace(): boolean {
    return true;
  }

  /** 声明的类型在本方言里实际会存成什么，用于与目录比较；默认原样返回。 */
  stored(declared: ColumnType): ColumnType {
    return declared;
  }

  /** 系统目录查询里第 n 个参数的占位符（从 1 起）。 */
  parameter(n: number): string {
    return this.dialect.placeholder(n);
  }

  // ---------- 建表 ----------

  /** 建表的语句：CREATE TABLE（含主键）、表和列的注释、索引；外键另由 {@link addForeignKey} 在最后建。 */
  createTable(t: TableDef): string[] {
    let sql = `${this.createKeyword} ${this.table(t)} (${t.columns.map((c) => this.columnDefinition(c)).join(", ")}`;
    if (t.primaryKey.length > 0) sql += `, PRIMARY KEY (${this.names(t.primaryKey)})`;
    sql += ")" + this.tableOptions(t);
    return [sql, ...this.comments(t), ...t.indexes.map((i) => this.createIndex(t, i))];
  }

  /** CREATE TABLE 的关键字；HANA 写成 `CREATE COLUMN TABLE`。 */
  protected get createKeyword(): string {
    return "CREATE TABLE";
  }

  /** 建表语句末尾的选项，例如 MySQL 的表注释；默认没有。 */
  protected tableOptions(_t: TableDef): string {
    return "";
  }

  /** 表和列的注释语句；默认写成 `COMMENT ON ... IS '...'`。 */
  protected comments(t: TableDef): string[] {
    const out: string[] = [];
    if (t.comment !== "") out.push(`COMMENT ON TABLE ${this.table(t)} IS ${this.literal(t.comment)}`);
    for (const c of t.columns) if (c.comment !== "") out.push(`COMMENT ON COLUMN ${this.table(t)}.${this.quote(c.name)} IS ${this.literal(c.comment)}`);
    return out;
  }

  /** 一列的定义：名字、类型、自增、默认值、NOT NULL。 */
  columnDefinition(c: ColumnDef): string {
    let sql = `${this.quote(c.name)} ${this.typeName(c.type)}`;
    if (c.identity) sql += " GENERATED BY DEFAULT AS IDENTITY";
    if (c.defaultValue !== "") sql += ` DEFAULT ${c.defaultValue}`;
    if (!c.nullable) sql += " NOT NULL";
    return sql;
  }

  // ---------- 改表 ----------

  /** 加一列。 */
  addColumn(t: TableDef, c: ColumnDef): string {
    return `ALTER TABLE ${this.table(t)} ADD COLUMN ${this.columnDefinition(c)}`;
  }

  /** 把列改成 c 的类型。 */
  alterType(t: TableDef, c: ColumnDef): string {
    return `ALTER TABLE ${this.table(t)} ALTER COLUMN ${this.quote(c.name)} TYPE ${this.typeName(c.type)}`;
  }

  /** 允许 NULL。 */
  dropNotNull(t: TableDef, c: ColumnDef): string {
    return `ALTER TABLE ${this.table(t)} ALTER COLUMN ${this.quote(c.name)} DROP NOT NULL`;
  }

  /** 不允许 NULL；已有 NULL 时数据库报错。 */
  setNotNull(t: TableDef, c: ColumnDef): string {
    return `ALTER TABLE ${this.table(t)} ALTER COLUMN ${this.quote(c.name)} SET NOT NULL`;
  }

  /** 改默认值为 c 的默认值。 */
  setDefault(t: TableDef, c: ColumnDef): string {
    return `ALTER TABLE ${this.table(t)} ALTER COLUMN ${this.quote(c.name)} SET DEFAULT ${c.defaultValue}`;
  }

  /** 把列 from 改名为 to。 */
  renameColumn(t: TableDef, from: string, to: string): string {
    return `ALTER TABLE ${this.table(t)} RENAME COLUMN ${this.quote(from)} TO ${this.quote(to)}`;
  }

  /** 建索引。 */
  createIndex(t: TableDef, i: IndexDef): string {
    return `CREATE ${i.unique ? "UNIQUE " : ""}INDEX ${this.quote(i.name)} ON ${this.table(t)} (${this.names(i.columns)})`;
  }

  /** 加外键。 */
  addForeignKey(t: TableDef, f: ForeignKeyDef): string {
    const target = f.referencedSchema === "" ? this.quote(f.referencedTable) : `${this.quote(f.referencedSchema)}.${this.quote(f.referencedTable)}`;
    return `ALTER TABLE ${this.table(t)} ADD CONSTRAINT ${this.quote(f.name)} FOREIGN KEY (${this.names(f.columns)}) REFERENCES ${target} (${this.names(f.referencedColumns)})`;
  }

  // ---------- 比较 ----------

  /** 默认值归一化后再比较：去掉外层括号、PostgreSQL 的 `::类型` 后缀和单引号，忽略大小写。 */
  normalizeDefault(value: string | null | undefined): string {
    if (value == null) return "";
    let v = value.trim();
    while (v.startsWith("(") && v.endsWith(")")) v = v.slice(1, -1).trim();
    v = withoutCast(v);
    if (v.startsWith("'") && v.endsWith("'") && v.length >= 2) v = v.slice(1, -1).replaceAll("''", "'");
    return v.toUpperCase();
  }

  // ---------- 共用 ----------

  /** 写出 `schema.表名`。 */
  protected table(t: TableDef): string {
    return t.schema === "" ? this.quote(t.name) : `${this.quote(t.schema)}.${this.quote(t.name)}`;
  }

  /** 按方言需要加引号的标识符。 */
  protected quote(identifier: string): string {
    return this.dialect.quote(identifier);
  }

  /** 逗号连接的列名。 */
  protected names(columns: readonly string[]): string {
    return columns.map((c) => this.quote(c)).join(", ");
  }

  /** 文本字面量。 */
  protected literal(text: string): string {
    return `'${text.replaceAll("'", "''")}'`;
  }
}

/**
 * 目录里去掉了引号的默认值（HANA、MySQL 的写法）还原成 SQL：文本、日期和时间列的常量加单引号，
 * 数字和 `CURRENT_*` 这类函数原样；没有默认值时返回空串。读回的模型因此与声明的写法一致，生成代码时三库相同。
 */
export function catalogDefault(raw: unknown, type: ColumnType): string {
  const v = catalogText(raw);
  if (v === "") return "";
  const quoted = ["TEXT", "CLOB", "DATE", "TIMESTAMP"].includes(type.kind) && !/^CURRENT_\w+(\(\d*\))?$/i.test(v);
  return quoted ? `'${v.replaceAll("'", "''")}'` : v;
}

/** PostgreSQL 目录里的默认值去掉 `::类型` 后缀，例如 `'open'::character varying` 读成 `'open'`。 */
export function withoutCast(raw: unknown): string {
  return catalogText(raw).replace(/::[a-zA-Z ]+(\(\d+(,\d+)?\))?(\[])?$/, "");
}

/** 目录里的数值（number、bigint、数字字符串都可能）转成 number；null 为 0。 */
export function catalogNumber(value: unknown): number {
  return value == null ? 0 : Number(value);
}

/** 目录里的文本；null 为空串。 */
export function catalogText(value: unknown): string {
  return value == null ? "" : String(value);
}

/** 把同一个外键或索引的多行（每行一列）合并：按 key 分组，保持出现顺序。 */
export function groupRows<T>(rows: readonly Record<string, unknown>[], key: (row: Record<string, unknown>) => string, build: (rows: Record<string, unknown>[]) => T): T[] {
  const groups = new Map<string, Record<string, unknown>[]>();
  for (const r of rows) {
    const k = key(r);
    const g = groups.get(k);
    if (g === undefined) groups.set(k, [r]);
    else g.push(r);
  }
  return [...groups.values()].map(build);
}
